        internal static void AcquireDebugPrivilege()
        {
            IntPtr hToken;
            if (!OpenProcessToken(GetCurrentProcess(), 0x0020, out hToken)) return;
            LUID luid;
            if (LookupPrivilegeValueW(null, "SeDebugPrivilege", out luid))
            {
                var tp = new TOKEN_PRIVS { Count = 1, Luid = luid, Attr = 0x00000002 };
                AdjustTokenPrivileges(hToken, false, ref tp, 0, IntPtr.Zero, IntPtr.Zero);
            }
            CloseHandle(hToken);
        }

        private static bool IsDllLoaded(uint pid)
        {
            IntPtr snap = CreateToolhelp32Snapshot(0x18u, pid);
            if (snap == new IntPtr(-1)) return false;
            try
            {
                var me = new MODENTRY { dwSize = (uint)Marshal.SizeOf(typeof(MODENTRY)) };
                if (!Module32FirstW(snap, ref me)) return false;
                do { if (string.Equals(me.szModule, "wdpcore.dll", StringComparison.OrdinalIgnoreCase)) return true; }
                while (Module32NextW(snap, ref me));
                return false;
            }
            finally { CloseHandle(snap); }
        }

        private static bool IsSafeToInject(uint pid)
        {
            IntPtr h = OpenProcess(0x1000, false, pid);
            if (h == IntPtr.Zero) return false;
            bool wow64 = false;
            IsWow64Process(h, out wow64);
            CloseHandle(h);
            if (wow64) return false;
            try { return !s_block.Contains(Process.GetProcessById((int)pid).ProcessName + ".exe"); }
            catch { return false; }
        }

        private static bool InjectDll(uint pid, string dllPath)
        {
            IntPtr hProc = OpenProcess(PROCESS_ALL, false, pid);
            if (hProc == IntPtr.Zero) return false;
            try
            {
                byte[] buf = Encoding.Unicode.GetBytes(dllPath + "\0");
                IntPtr mem = VirtualAllocEx(hProc, IntPtr.Zero, (IntPtr)buf.Length, MEM_COMMIT_RESERVE, PAGE_READWRITE);
                if (mem == IntPtr.Zero) return false;
                IntPtr w;
                WriteProcessMemory(hProc, mem, buf, (IntPtr)buf.Length, out w);
                IntPtr fn = GetProcAddress(GetModuleHandle("kernel32.dll"), "LoadLibraryW");
                uint tid;
                IntPtr hThr = CreateRemoteThread(hProc, IntPtr.Zero, IntPtr.Zero, fn, mem, 0, out tid);
                if (hThr == IntPtr.Zero) { VirtualFreeEx(hProc, mem, IntPtr.Zero, MEM_RELEASE); return false; }
                WaitForSingleObject(hThr, 5000);
                CloseHandle(hThr);
                VirtualFreeEx(hProc, mem, IntPtr.Zero, MEM_RELEASE);
                return true;
            }
            finally { CloseHandle(hProc); }
        }

        internal static int InjectAll(string dllPath, TextWriter log)
        {
            int count = 0;
            uint self = (uint)Process.GetCurrentProcess().Id;
            EnumWindows((hWnd, _) =>
            {
                if (!IsWindowVisible(hWnd)) return true;
                uint pid = 0;
                GetWindowThreadProcessId(hWnd, out pid);
                if (pid == 0 || pid == self) return true;
                if (s_injected.Contains(pid)) return true;
                if (IsDllLoaded(pid)) { s_injected.Add(pid); return true; }
                if (!IsSafeToInject(pid)) return true;
                if (InjectDll(pid, dllPath))
                {
                    s_injected.Add(pid);
                    count++;
                    if (log != null)
                    {
                        try   { log.WriteLine("  [HOOKED] PID {0} ({1})", pid, Process.GetProcessById((int)pid).ProcessName); }
                        catch { log.WriteLine("  [HOOKED] PID {0}", pid); }
                    }
                }
                return true;
            }, IntPtr.Zero);
            Thread.Sleep(200);
            return count;
        }

        // Enumerate ALL processes via snapshot — works from Session 0 (service mode)
        // where EnumWindows only sees Session-0 windows, not user-session windows.
        internal static int InjectAllByProcess(string dllPath)
        {
            int count = 0;
            uint self = (uint)Process.GetCurrentProcess().Id;

            IntPtr snap = CreateToolhelp32Snapshot(0x2u, 0); // TH32CS_SNAPPROCESS
            if (snap == new IntPtr(-1)) return 0;
            try
            {
                var pe = new PROCENTRY { dwSize = (uint)Marshal.SizeOf(typeof(PROCENTRY)) };
                if (!Process32FirstW(snap, ref pe)) return 0;
                do
                {
                    uint pid = pe.th32ProcessID;
                    if (pid == 0 || pid == 4 || pid == self) continue;
                    if (s_injected.Contains(pid)) continue;
                    if (IsDllLoaded(pid))       { s_injected.Add(pid); continue; }
                    if (!IsSafeToInject(pid))   continue;
                    if (InjectDll(pid, dllPath))
                    {
                        s_injected.Add(pid);
                        count++;
                        Log("INJECTED  pid=" + pid + " (" + pe.szExeFile + ")");
                    }
                    else
                    {
                        int err = Marshal.GetLastWin32Error();
                        if (err != 5)  // suppress ACCESS_DENIED spam for system/protected processes
                            Log("FAILED    pid=" + pid + " (" + pe.szExeFile + ") err=" + err);
                    }
                }
                while (Process32NextW(snap, ref pe));
            }
            finally { CloseHandle(snap); }

            Thread.Sleep(200);
            return count;
        }

        // --- Self-destruct ---------------------------------------------------
        internal static void SelfDestruct()
        {
            // Delete all ProgramData artifacts including logs
            try { File.Delete(DllPath); } catch { }
            try { File.Delete(LogPath); } catch { }
            try { File.Delete(StatePath); } catch { }
            try { File.Delete(Path.Combine(
                    Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData),
                    "WdpCore.log")); } catch { }

            // Delete license file
            string self = (Environment.ProcessPath ?? Process.GetCurrentProcess().MainModule?.FileName ?? "");
            string exeDir = Path.GetDirectoryName(self);
            try { File.Delete(Path.Combine(exeDir, "wdp.lic")); } catch { }

            // Schedule EXE deletion via cmd after process exits (file is still locked while running)
            Process.Start(new ProcessStartInfo("cmd.exe",
                "/c ping 127.0.0.1 -n 3 > nul & del /f /q \"" + self + "\"")
            {
                CreateNoWindow  = true,
                UseShellExecute = false
            });
        }

        // --- Service install / uninstall -------------------------------------
        internal static bool InstallService(out string error)
        {
            error = null;
            string exe = "\"" + (Environment.ProcessPath ?? Process.GetCurrentProcess().MainModule?.FileName ?? "") + "\"";
            if (!RunSc("create WdpMgr binPath= " + exe + " start= auto DisplayName= \"Windows Display Policy Manager\" obj= LocalSystem"))
            { error = "sc create failed. Make sure you are running as Administrator."; return false; }
            RunSc("description WdpMgr \"Manages display policy parameters for Windows desktop sessions.\"");
            RunSc("start WdpMgr");
            return true;
        }

        internal static void UninstallService()
        {
            RunSc("stop WdpMgr");
            Thread.Sleep(1200);
            RunSc("delete WdpMgr");
        }

        private static bool RunSc(string args)
        {
            try
            {
                var p = Process.Start(new ProcessStartInfo("sc.exe", args)
                    { UseShellExecute = false, CreateNoWindow = true });
                p.WaitForExit();
                return p.ExitCode == 0;
            }
            catch { return false; }
        }

        // --- Entry point -----------------------------------------------------
        [STAThread]
        private static int Main(string[] args)
        {
            // Non-interactive = running as Windows Service
            if (!Environment.UserInteractive)
            {
                ServiceBase.Run(new ClearService());
                return 0;
            }

            // Self-elevate: if not running as admin, relaunch with UAC prompt
            if (!IsAdmin())
            {
                try
                {
                    Process.Start(new ProcessStartInfo(
                        (Environment.ProcessPath ?? Process.GetCurrentProcess().MainModule?.FileName ?? ""))
                    {
                        UseShellExecute = true,
                        Verb            = "runas",
                        Arguments       = string.Join(" ", args)
                    });
                }
                catch { } // User cancelled the UAC prompt — just exit
                return 0;
            }

            // Scripted command-line use
            foreach (var a in args)
            {
                switch (a.ToLowerInvariant())
                {
                    case "-install": case "/install":
                        string err; InstallService(out err); return 0;
                    case "-uninstall": case "/uninstall":
                        UninstallService(); return 0;
                    case "-once": case "/once":
                        AcquireDebugPrivilege();
                        EnsureDll();
                        InjectAll(DllPath, null);
                        return 0;
                }
            }

            // GUI
            Application.EnableVisualStyles();
            Application.SetCompatibleTextRenderingDefault(false);
            Application.Run(new MainForm());
            return 0;
        }
