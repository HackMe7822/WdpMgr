        private void DoInstall()
        {
            if (!Program.IsAdmin()) { MessageBox.Show("Please run as Administrator.", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error); return; }

            Program.Log("--- Install button clicked ---");
            LicenseData lic;
            bool hasLic = Program.ReadLicense(out lic);
            Program.Log("ReadLicense: " + hasLic + (hasLic ? "  id=" + lic.Id + "  type=" + lic.Type : "  (not found)"));

            if (!hasLic)
            {
                MessageBox.Show(
                    "No license found in this EXE.\n\n" +
                    "Make sure you downloaded the EXE from the admin panel\n" +
                    "(Licenses tab → ⬇ EXE), not the raw WdpMgr.exe from the repo.\n\n" +
                    "Log: " + Program.LogPath,
                    "License Not Found", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }

            bool sigOk = Program.VerifyLicense(lic);
            Program.Log("VerifyLicense: " + sigOk);

            if (!sigOk)
            {
                MessageBox.Show(
                    "License signature verification failed.\n\n" +
                    "Possible causes:\n" +
                    "• Server was reinstalled (RSA key changed) — re-download the EXE\n" +
                    "• EXE was modified after download\n\n" +
                    "Details: " + Program.LogPath,
                    "Invalid License", MessageBoxButtons.OK, MessageBoxIcon.Error);
                return;
            }

            // Pre-flight server check — catch revoked/expired/no-seats BEFORE installing
            SetBusy("Checking license with server...");
            string preCheck = Program.CheckIn(lic);
            Program.Log("Pre-flight CheckIn: " + preCheck);
            if (preCheck == "revoked")
            {
                RefreshStatus();
                MessageBox.Show(
                    "This license or machine has been revoked by your admin.\n\n" +
                    "This EXE can no longer be used on this machine.\n" +
                    "Contact your admin to get a new license EXE.",
                    "Revoked", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }
            if (preCheck == "expired")
            {
                RefreshStatus();
                MessageBox.Show(
                    "This license has expired on the server.\n\n" +
                    "Ask your admin to extend the expiry, then re-download the EXE.",
                    "License Expired", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }
            if (preCheck == "wrong_machine")
            {
                RefreshStatus();
                MessageBox.Show(
                    "Max machines/seats reached for this license.\n\n" +
                    "Contact your admin to increase the seat limit or get a new license.",
                    "No Seats Available", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return;
            }
            if (preCheck == "invalid")
            {
                RefreshStatus();
                MessageBox.Show(
                    "Server rejected this license as invalid.\n\n" +
                    "Try re-downloading the EXE from the admin panel.\n\nLog: " + Program.LogPath,
                    "License Invalid", MessageBoxButtons.OK, MessageBoxIcon.Error);
                return;
            }
            // preCheck == "offline" → server temporarily unreachable; allow install and let the service retry

            // Auto-remove any leftover stopped service entry before fresh install
            if (Program.GetServiceStatus() != "Not installed")
            {
                SetBusy("Removing old service entry...");
                Program.Log("Removing existing service entry before reinstall");
                Program.UninstallService();
                Thread.Sleep(1500);
            }

            SetBusy("Installing service, please wait...");
            string err;
            bool ok = Program.InstallService(out err);
            Thread.Sleep(900);
            RefreshStatus();
            if (ok) MessageBox.Show("Service installed and started.\nDisplay affinity bypass is now active.", "Success", MessageBoxButtons.OK, MessageBoxIcon.Information);
            else    MessageBox.Show("Install failed:\n" + err + "\n\nLog: " + Program.LogPath, "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
        }

        private void DoUninstall()
        {
            if (!Program.IsAdmin()) { MessageBox.Show("Please run as Administrator.", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error); return; }
            if (MessageBox.Show("Stop and remove the Windows Display Policy Manager service?\n\nThis will also permanently delete the application.", "Confirm", MessageBoxButtons.YesNo, MessageBoxIcon.Question) != DialogResult.Yes) return;
            SetBusy("Stopping service...");
            Program.UninstallService();
            SetBusy("Removing files...");
            Thread.Sleep(900);
            MessageBox.Show("Service removed. The application will now delete itself.", "Done", MessageBoxButtons.OK, MessageBoxIcon.Information);
            Program.SelfDestruct();
            Application.Exit();
        }

        private void DoRunOnce()
        {
            LicenseData licRO;
            if (!Program.ReadLicense(out licRO) || !Program.VerifyLicense(licRO))
            {
                MessageBox.Show("No valid license found in this EXE.", "License Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
                return;
            }
            if (!string.IsNullOrEmpty(licRO.Expiry))
            {
                DateTime expDtRO;
                if (DateTime.TryParse(licRO.Expiry, out expDtRO) && expDtRO.ToUniversalTime() < DateTime.UtcNow)
                {
                    MessageBox.Show(
                        "This license expired on " + expDtRO.ToLocalTime().ToString("yyyy-MM-dd HH:mm") + ".\n\n" +
                        "Ask your admin to extend the license, then re-download the EXE.",
                        "License Expired", MessageBoxButtons.OK, MessageBoxIcon.Warning);
                    return;
                }
            }
            try
            {
                Cursor = Cursors.WaitCursor;
                Program.AcquireDebugPrivilege();
                Program.EnsureDll();
                int n = Program.InjectAll(Program.DllPath, null);
                Cursor = Cursors.Default;
                Program.Log("RunOnce: injected " + n + " new process(es)");
                MessageBox.Show(n > 0
                    ? string.Format("Hooked {0} new process(es).\nDisplay affinity cleared.", n)
                    : "No new processes to hook.\nCheck the log for details (View Log button).",
                    "Done", MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (Exception ex)
            {
                Cursor = Cursors.Default;
                Program.Log("RunOnce EXCEPTION: " + ex);
                MessageBox.Show("Error: " + ex.Message +
                    "\n\nRun as Administrator and try again.", "Error",
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void DoViewLog()
        {
            if (!File.Exists(Program.LogPath))
            {
                MessageBox.Show("No log file yet.\nInstall the service or click Run Once first.",
                    "Log", MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }
            Process.Start("notepad.exe", Program.LogPath);
        }
