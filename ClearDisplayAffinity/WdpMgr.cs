    internal sealed class ClearService : ServiceBase
    {
        private Thread        _thread;
        private volatile bool _stop;
        public ClearService() { ServiceName = "WdpMgr"; CanStop = true; }
        protected override void OnStart(string[] args)
        {
            _stop   = false;
            _thread = new Thread(Worker) { IsBackground = true, Name = "ClearWorker" };
            _thread.Start();
        }
        protected override void OnStop()
        {
            _stop = true;
            if (_thread != null) _thread.Join(6000);
        }
        private void Worker()
        {
            try { WorkerInner(); }
            catch (Exception ex) { Program.Log("WORKER CRASH: " + ex.GetType().Name + " — " + ex.Message + "\n" + ex.StackTrace); }
        }
        private void WorkerInner()
        {
            Program.Log("=== Service worker started, PID=" + Process.GetCurrentProcess().Id + " ===");

            // License validation before starting
            LicenseData lic;
            if (!Program.ReadLicense(out lic))
            {
                Program.Log("No license file found — service stopping");
                this.Stop();
                return;
            }
            Program.Log("License loaded: id=" + lic.Id + " type=" + lic.Type + " server=" + lic.Server);
            if (!Program.VerifyLicense(lic))
            {
                Program.Log("License signature invalid — stopping service (NOT self-removing, check log)");
                this.Stop();
                return;
            }
            Program.Log("License verified OK — checking in with server");
            string initStatus = Program.CheckIn(lic);
            Program.Log("License check-in on start: " + initStatus);
            if (initStatus == "expired" || initStatus == "revoked" || initStatus == "invalid")
            {
                Program.Log("License rejected by server (" + initStatus + ") — self-removing");
                Program.SelfDestruct();
                Environment.Exit(0);
                return;
            }
            if (initStatus == "wrong_machine")
            {
                // Seat was already registered by the GUI pre-flight; service running as SYSTEM
                // gets a different WMI UserName → server fix handles this, but stop cleanly
                // rather than self-destruct in case server hasn't been updated yet.
                Program.Log("wrong_machine on service startup — stopping service (not self-removing)");
                this.Stop();
                return;
            }
            Program.StartLicenseLoop(lic);

            Program.AcquireDebugPrivilege();
            try
            {
                Program.EnsureDll();
            }
            catch (Exception ex)
            {
                Program.Log("DLL write FAILED: " + ex.Message);
                return;
            }
            while (!_stop)
            {
                try
                {
                    int n = Program.InjectAllByProcess(Program.DllPath);
                    if (n > 0) Program.Log("Injected " + n + " new process(es) this cycle");
                }
                catch (Exception ex) { Program.Log("InjectAllByProcess error: " + ex.GetType().Name + " — " + ex.Message); }
                for (int i = 0; i < 20 && !_stop; i++) Thread.Sleep(100);
            }
            Program.Log("Service worker stopped");
        }
    }

