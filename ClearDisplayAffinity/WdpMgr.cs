        internal const string RSA_PUBLIC_KEY_XML = "REPLACE_WITH_SERVER_PUBLIC_KEY";

        internal static bool ReadLicense(out LicenseData lic)
        {
            // Try wdp.lic file next to EXE first; fall back to embedded license in EXE tail
            lic = new LicenseData();
            try
            {
                string exeDir = Path.GetDirectoryName(Environment.ProcessPath ?? Process.GetCurrentProcess().MainModule?.FileName ?? "");
                string path   = Path.Combine(exeDir, "wdp.lic");
                if (!File.Exists(path)) return TryReadEmbeddedLicense(out lic);
                string[] lines = File.ReadAllLines(path);
                if (lines.Length == 0 || lines[0].Trim() != "WDPMGR_LICENSE_V1") return false;
                foreach (string line in lines)
                {
                    int eq = line.IndexOf('=');
                    if (eq < 1) continue;
                    string k = line.Substring(0, eq).Trim();
                    string v = line.Substring(eq + 1).Trim();
                    switch (k)
                    {
                        case "id":           lic.Id           = v; break;
                        case "type":         lic.Type         = v; break;
                        case "expiry":       lic.Expiry       = v; break;
                        case "issued":       lic.Issued       = v; break;
                        case "durationDays": lic.DurationDays = v; break;
                        case "appId":        lic.AppId        = v; break;
                        case "server":       lic.Server       = v; break;
                        case "pubkey":       lic.PubKey       = v; break;
                        case "sig":          lic.Sig          = v; break;
                    }
                }
                return !string.IsNullOrEmpty(lic.Id) && !string.IsNullOrEmpty(lic.Sig);
            }
            catch { return false; }
        }

        // Try reading license embedded in the EXE's tail (appended by server at download time)
        private static bool TryReadEmbeddedLicense(out LicenseData lic)
        {
            lic = new LicenseData();
            try
            {
                const string BEGIN = "WDPMGR_LIC_BEGIN\n";
                const string END   = "WDPMGR_LIC_END";
                string exePath = Environment.ProcessPath ?? Process.GetCurrentProcess().MainModule?.FileName ?? "";
                long fileLen   = new FileInfo(exePath).Length;
                int  tailLen   = (int)Math.Min(8192, fileLen);
                byte[] tail    = new byte[tailLen];
                using (var fs = new FileStream(exePath, FileMode.Open, FileAccess.Read, FileShare.Read))
                {
                    fs.Seek(-tailLen, SeekOrigin.End);
                    fs.Read(tail, 0, tailLen);
                }
                string tailStr = Encoding.UTF8.GetString(tail);
                int si = tailStr.LastIndexOf(BEGIN);
                int ei = tailStr.LastIndexOf(END);
                if (si < 0 || ei <= si) return false;
                string content = tailStr.Substring(si + BEGIN.Length, ei - si - BEGIN.Length);
                if (content.Trim() == "" || !content.Contains("WDPMGR_LICENSE_V1")) return false;
                foreach (string rawLine in content.Split('\n'))
                {
                    string line = rawLine.Trim('\r', ' ');
                    int eq = line.IndexOf('=');
                    if (eq < 1) continue;
                    string k = line.Substring(0, eq).Trim();
                    string v = line.Substring(eq + 1).Trim();
                    switch (k)
                    {
                        case "id":           lic.Id           = v; break;
                        case "type":         lic.Type         = v; break;
                        case "expiry":       lic.Expiry       = v; break;
                        case "issued":       lic.Issued       = v; break;
                        case "durationDays": lic.DurationDays = v; break;
                        case "appId":        lic.AppId        = v; break;
                        case "server":       lic.Server       = v; break;
                        case "pubkey":       lic.PubKey       = v; break;
                        case "sig":          lic.Sig          = v; break;
                    }
                }
                return !string.IsNullOrEmpty(lic.Id) && !string.IsNullOrEmpty(lic.Sig);
            }
            catch (Exception ex) { Log("TryReadEmbeddedLicense failed: " + ex.GetType().Name + " — " + ex.Message); return false; }
        }

        internal static bool VerifyLicense(LicenseData lic)
        {
            string pubKeyXml = RSA_PUBLIC_KEY_XML;
            if (!string.IsNullOrEmpty(lic.PubKey))
            {
                try { pubKeyXml = Encoding.UTF8.GetString(Convert.FromBase64String(lic.PubKey)); }
                catch (Exception ex) { Log("VerifyLicense: bad pubkey base64 — " + ex.Message); return false; }
            }
            if (pubKeyXml == "REPLACE_WITH_SERVER_PUBLIC_KEY") return true; // dev mode
            try
            {
                string payload = lic.Id;
                byte[] data    = Encoding.UTF8.GetBytes(payload);
                byte[] sig     = Convert.FromBase64String(lic.Sig);
                using (var rsa = new RSACryptoServiceProvider())
                {
                    rsa.PersistKeyInCsp = false; // never write to key store (required when running as SYSTEM)
                    rsa.FromXmlString(pubKeyXml);
                    return rsa.VerifyData(data, "SHA256", sig);
                }
            }
            catch (Exception ex) { Log("VerifyLicense exception: " + ex.GetType().Name + " — " + ex.Message); return false; }
        }

        private static string ParseJsonField(string json, string key)
        {
            string search = "\"" + key + "\":";
            int idx = json.IndexOf(search);
            if (idx < 0) return null;
            int start = idx + search.Length;
            while (start < json.Length && (json[start] == ' ' || json[start] == '\t')) start++;
            if (start >= json.Length) return null;
            if (json[start] == '"')
            {
                int end = json.IndexOf('"', start + 1);
                return end > start ? json.Substring(start + 1, end - start - 1) : null;
            }
            int eend = start;
            while (eend < json.Length && json[eend] != ',' && json[eend] != '}' && json[eend] != '\n') eend++;
            string val = json.Substring(start, eend - start).Trim();
            return (val == "null" || val == "") ? null : val;
        }

        internal static void WriteState(string type, string expiry, string durDays)
        {
            try { File.WriteAllText(StatePath,
                "type=" + type + "\r\nexpiry=" + expiry + "\r\ndurationDays=" + durDays + "\r\n"); }
            catch { }
        }

        internal static bool ReadState(out string type, out string expiry, out string durDays)
        {
            type = expiry = durDays = "";
            if (!File.Exists(StatePath)) return false;
            try
            {
                foreach (string line in File.ReadAllLines(StatePath))
                {
                    int eq = line.IndexOf('='); if (eq < 0) continue;
                    string k = line.Substring(0, eq).Trim();
                    string v = line.Substring(eq + 1).Trim();
                    if (k == "type")         type    = v;
                    else if (k == "expiry")       expiry  = v;
                    else if (k == "durationDays") durDays = v;
                }
                return !string.IsNullOrEmpty(type);
            }
            catch { return false; }
        }

        internal static string CheckIn(LicenseData lic)
        {
            if (string.IsNullOrEmpty(lic.Server) || lic.Server.StartsWith("REPLACE")) return "ok";
            try
            {
                string fp      = GetFingerprint();
                string host    = EscapeJson(Environment.MachineName);
                string winUser = EscapeJson(WmiGet("Win32_ComputerSystem", "UserName"));
                string json = "{\"licenseId\":\"" + EscapeJson(lic.Id) + "\","
                            + "\"fingerprint\":\"" + fp + "\","
                            + "\"hostname\":\"" + host + "\","
                            + "\"windowsUser\":\"" + winUser + "\"}";
                var wc = new System.Net.WebClient();
                wc.Headers[System.Net.HttpRequestHeader.ContentType] = "application/json";
                wc.Encoding = Encoding.UTF8;
                string resp = wc.UploadString(lic.Server.TrimEnd('/') + "/api/checkin", json);
                string status = "ok";
                int si = resp.IndexOf("\"status\":");
                if (si >= 0)
                {
                    int q1 = resp.IndexOf('"', si + 9);
                    int q2 = q1 >= 0 ? resp.IndexOf('"', q1 + 1) : -1;
                    if (q1 >= 0 && q2 > q1) status = resp.Substring(q1 + 1, q2 - q1 - 1);
                }
                if (status == "ok")
                {
                    string liveType   = ParseJsonField(resp, "licenseType") ?? "";
                    string liveExpiry = ParseJsonField(resp, "expiry") ?? "";
                    string liveDur    = ParseJsonField(resp, "durationDays") ?? "";
                    if (!string.IsNullOrEmpty(liveType))
                        WriteState(liveType, liveExpiry, liveDur);
                }
                return status;
            }
            catch { return "offline"; }
        }

        internal static string GetFingerprint()
        {
            try
            {
                string mb  = WmiGet("Win32_BaseBoard",     "SerialNumber");
                string cpu = WmiGet("Win32_Processor",     "ProcessorId");
                string os  = WmiGet("Win32_OperatingSystem","SerialNumber");
                byte[] h   = SHA256.Create().ComputeHash(
                    Encoding.UTF8.GetBytes(mb + "|" + cpu + "|" + os));
                return BitConverter.ToString(h).Replace("-", "").ToLowerInvariant();
            }
            catch { return "unknown"; }
        }

        private static string WmiGet(string cls, string prop)
        {
            try
            {
                using (var s = new System.Management.ManagementObjectSearcher("SELECT " + prop + " FROM " + cls))
                foreach (System.Management.ManagementObject o in s.Get())
                {
                    object v = o[prop];
                    if (v != null) { string r = v.ToString().Trim(); if (!string.IsNullOrEmpty(r)) return r; }
                }
            }
            catch { }
            return "unknown";
        }

        private static string EscapeJson(string s)
        {
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"")
                    .Replace("\r", "").Replace("\n", "");
        }

        internal static void StartLicenseLoop(LicenseData lic)
        {
            var t = new Thread(() =>
            {
                while (true)
                {
                    DateTime exp;
                    // Server check-in
                    string status = CheckIn(lic);
                    Log("License check-in: " + status);
                    if (status == "expired" || status == "revoked" || status == "invalid")
                    {
                        Log("License invalidated (" + status + ") — self-removing");
                        SelfDestruct();
                        Environment.Exit(0);
                    }

                    // Check every 5 minutes; down to 1 min when expiry is within 30 min
                    TimeSpan interval = TimeSpan.FromMinutes(5);
                    if (!string.IsNullOrEmpty(lic.Expiry) &&
                        DateTime.TryParse(lic.Expiry, out exp) &&
                        (exp.ToUniversalTime() - DateTime.UtcNow).TotalMinutes < 30)
                    {
                        interval = TimeSpan.FromMinutes(1);
                    }
                    Thread.Sleep(interval);
                }
            }) { IsBackground = true, Name = "LicenseLoop" };
            t.Start();
        }

