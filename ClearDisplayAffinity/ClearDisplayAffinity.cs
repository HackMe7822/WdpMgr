        private void RefreshStatus()
        {
            string st = Program.GetServiceStatus();
            _lblStatus.Text       = "Service status:  " + st;
            bool inst = st != "Not installed";
            _btnInstall.Enabled   = !inst;
            _btnUninstall.Enabled = inst;
        }

        private void DoInstall()
        {
            if (!Program.IsAdmin()) { MessageBox.Show("Please run as Administrator.", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error); return; }
            Cursor = Cursors.WaitCursor;
            string err;
            bool ok = Program.InstallService(out err);
            Thread.Sleep(900);
            RefreshStatus();
            Cursor = Cursors.Default;
            if (ok) MessageBox.Show("Service installed and started.\nDisplay affinity bypass is now active.", "Success", MessageBoxButtons.OK, MessageBoxIcon.Information);
            else    MessageBox.Show("Install failed:\n" + err, "Error", MessageBoxButtons.OK, MessageBoxIcon.Error);
        }

        private void DoUninstall()
        {
            if (!Program.IsAdmin()) { MessageBox.Show("Please run as Administrator.", "Error", MessageBoxButtons.OK, MessageBoxIcon.Error); return; }
            if (MessageBox.Show("Stop and remove the Windows Display Policy Manager service?", "Confirm", MessageBoxButtons.YesNo, MessageBoxIcon.Question) != DialogResult.Yes) return;
            Cursor = Cursors.WaitCursor;
            Program.UninstallService();
            Thread.Sleep(900);
            RefreshStatus();
            Cursor = Cursors.Default;
            MessageBox.Show("Service removed successfully.", "Done", MessageBoxButtons.OK, MessageBoxIcon.Information);
        }

        private void DoRunOnce()
        {
            try
            {
                Cursor = Cursors.WaitCursor;
                Program.AcquireDebugPrivilege();
                Program.EnsureDll();
                int n = Program.InjectAll(Program.DllPath, null);
                Cursor = Cursors.Default;
                Program.Log("RunOnce: injected " + n + " new process(es)");
                MessageBox.Show(n > 0
                    ? string.Format("Hooked {0} new process(es).\nDisplay affinity cleared.", n)
                    : "No new processes to hook.\nCheck the log for details (View Log button).",
                    "Done", MessageBoxButtons.OK, MessageBoxIcon.Information);
            }
            catch (Exception ex)
            {
                Cursor = Cursors.Default;
                Program.Log("RunOnce EXCEPTION: " + ex);
                MessageBox.Show("Error: " + ex.Message +
                    "\n\nRun as Administrator and try again.", "Error",
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }

        private void DoViewLog()
        {
            if (!File.Exists(Program.LogPath))
            {
                MessageBox.Show("No log file yet.\nInstall the service or click Run Once first.",
                    "Log", MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }
            Process.Start("notepad.exe", Program.LogPath);
        }
